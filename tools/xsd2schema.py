#!/usr/bin/env python3
"""Generates the DPS element tree used by nfse (src/schema/*.txt) from the
official XSD package: DPS_v1.01.xsd and tiposComplexos_v1.01.xsd.

Usage: tools/xsd2schema.py <dir with the XSDs> <output .txt>

Output: one element per line, "indent name min max type"; "(choice)" or
"(choice?)" (optional choice) groups the elements indented below it.
"""
import sys
import xml.etree.ElementTree as ET

XS = "{http://www.w3.org/2001/XMLSchema}"


def load(directory):
    types = {}
    for name in ["tiposComplexos_v1.01.xsd", "DPS_v1.01.xsd"]:
        root = ET.parse(f"{directory}/{name}").getroot()
        for ct in root.iter(XS + "complexType"):
            if ct.get("name"):
                types[ct.get("name")] = ct
    return types


def occurs(node):
    mn = node.get("minOccurs", "1")
    mx = node.get("maxOccurs", "1")
    return mn, "*" if mx == "unbounded" else mx


def emit(out, types, particle, indent, stack):
    tag = particle.tag[len(XS):]
    pad = "  " * indent
    if tag == "element":
        name, ty = particle.get("name"), particle.get("type")
        if name is None:
            raise SystemExit(f"element without a name: {particle.attrib}")
        mn, mx = occurs(particle)
        out.append(f"{pad}{name} {mn} {mx} {ty}")
        if ty in types:
            if ty in stack:
                raise SystemExit(f"recursive type {ty}")
            emit_type(out, types, types[ty], indent + 1, stack + [ty])
    elif tag == "sequence":
        if occurs(particle) != ("1", "1"):
            raise SystemExit(f"repeated sequence not supported: {particle.attrib}")
        for child in particle:
            if child.tag.startswith(XS) and child.tag != XS + "annotation":
                emit(out, types, child, indent, stack)
    elif tag == "choice":
        mn, mx = occurs(particle)
        if mx != "1":
            raise SystemExit(f"repeated choice not supported: {particle.attrib}")
        out.append(f"{pad}(choice{'?' if mn == '0' else ''})")
        for child in particle:
            if child.tag == XS + "annotation":
                continue
            if child.tag != XS + "element":
                raise SystemExit(f"choice of {child.tag} not supported under {stack[-1]}")
            emit(out, types, child, indent + 1, stack)
    elif tag in ("annotation", "attribute"):
        pass
    elif tag == "any":
        pass  # xs:any (Signature): not part of infDPS content
    else:
        raise SystemExit(f"unsupported {tag} under {stack[-1]}")


def emit_type(out, types, ct, indent, stack):
    for child in ct:
        if child.tag in (XS + "sequence", XS + "choice"):
            emit(out, types, child, indent, stack)
        elif child.tag in (XS + "annotation", XS + "attribute"):
            continue
        else:
            raise SystemExit(f"unsupported {child.tag} in {stack[-1]}")


def main():
    directory, target = sys.argv[1], sys.argv[2]
    types = load(directory)
    out = [
        "# Generated by tools/xsd2schema.py from the DPS v1.01 XSD; do not edit.",
        '# indent name min max type; "(choice)" / "(choice?)" group the elements below it.',
        "infDPS 1 1 TCInfDPS",
    ]
    emit_type(out, types, types["TCInfDPS"], 1, ["TCInfDPS"])
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
